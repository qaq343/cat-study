import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { STORAGE_KEY, createInitialProgress, startSession, flattenCourses } from '../js/core.js';
import { NOTES_KEY, LEGACY_PLAN_KEY, readLessonNotes, removeLegacyPlan, switchCourse } from '../js/course-navigation.js';
const courses = JSON.parse(await readFile(new URL('../data/courses.json', import.meta.url), 'utf8'));
const now = new Date('2026-10-15T09:00:00+08:00');
function store(initial = {}) { const map = new Map(Object.entries(initial)); return { getItem: key => map.has(key) ? map.get(key) : null, setItem: (key, value) => map.set(key, value), removeItem: key => map.delete(key) }; }
const oldNote = { mastery: '能解释', note: '保留真实备注', savedSession: { lessonId: '9:2:2.1', state: 'PAUSED', activeElapsedMs: 65000, startedAt: now.toISOString(), activeSegmentStartedAt: null } };
const storage = store({ [LEGACY_PLAN_KEY]: JSON.stringify({ lessonNotes: { '9:2:2.1': oldNote }, days: { stale: true }, tasks: { practice: true } }), unrelated: 'keep' });
removeLegacyPlan(storage);
assert.equal(storage.getItem(LEGACY_PLAN_KEY), null);
assert.deepEqual(readLessonNotes(storage).lessons['9:2:2.1'], oldNote);
assert.equal(storage.getItem('unrelated'), 'keep');
assert.equal(JSON.parse(storage.getItem(NOTES_KEY)).days, undefined, '旧排期不混入新课节备注');
const progress = createInitialProgress(courses, now), initial = JSON.stringify({ completed: progress.completedLessonIds, history: progress.history, settings: progress.settings });
startSession(progress, now); const oldKey = progress.currentLessonId;
switchCourse(progress, courses, storage, '9:2:2.1', new Date(+now + 10000));
assert.equal(progress.currentLessonId, '9:2:2.1', '直接跨阶段，无需完成旧课');
assert.equal(progress.activeSession.activeElapsedMs, 65000, '恢复已暂存目标课');
assert.equal(progress.activeSession.state, 'PAUSED');
assert.equal(readLessonNotes(storage).lessons[oldKey].savedSession.activeElapsedMs, 10000, '原正在计时课节先保存');
switchCourse(progress, courses, storage, oldKey, new Date(+now + 20000));
assert.equal(progress.activeSession.activeElapsedMs, 10000);
assert.equal(progress.activeSession.state, 'PAUSED');
switchCourse(progress, courses, storage, '9:6:6.2', new Date(+now + 30000));
assert.equal(progress.activeSession, null, '新课尚未开始，不误归属旧课计时');
assert.equal(JSON.stringify({ completed: progress.completedLessonIds, history: progress.history, settings: progress.settings }), initial);
assert.throws(() => switchCourse(progress, courses, storage, 'not-a-lesson', now));
assert.ok(flattenCourses(courses, { requiredOnly: true }).some(item => item.key === progress.currentLessonId));
const broken = store({ [LEGACY_PLAN_KEY]: '{broken' });
assert.throws(() => removeLegacyPlan(broken)); assert.equal(broken.getItem(LEGACY_PLAN_KEY), '{broken', '异常原数据不删除');
const noSpace = store({ [LEGACY_PLAN_KEY]: JSON.stringify({ lessonNotes: { 'x': oldNote } }) });
noSpace.setItem = () => { throw new Error('quota'); };
assert.throws(() => removeLegacyPlan(noSpace)); assert.ok(noSpace.getItem(LEGACY_PLAN_KEY), '备注未保存成功时禁止删除旧计划');
console.log('✓ 旧排期安全移除、备注/暂存计时保留、跨阶段自由选择、切回续计、完成数/历史不变及写入失败保护通过');
