import assert from 'node:assert/strict';
import { PRACTICE_KEY, activityState, createPractice, loadPractice, checkpointPractice, startPractice, pausePractice, finishPractice, practiceToday } from '../js/practice.js';
assert.equal(activityState({ activeSession: { state: 'PAUSED' } }, { active: { state: 'STUDYING' } }), 'STUDYING', '暂停的课程不能覆盖练习进行中');
assert.equal(activityState({ activeSession: { state: 'STUDYING' } }, { active: { state: 'PAUSED' } }), 'STUDYING');
assert.equal(activityState(null, { active: { state: 'PAUSED' } }), 'PAUSED');
assert.equal(activityState(null, null), 'IDLE');
const state = createPractice();
const at = value => new Date(`2026-10-14T${value}+08:00`);
assert.equal(startPractice(state, '分组练习', null, at('10:00:00')), true);
checkpointPractice(state, at('10:01:00'));
pausePractice(state, at('10:02:00'));
checkpointPractice(state, at('10:30:00'));
assert.equal(state.active.elapsedMs, 120000);
startPractice(state, '', null, at('10:31:00'));
checkpointPractice(state, at('10:32:00'));
const interrupted = loadPractice({ getItem: key => { assert.equal(key, PRACTICE_KEY); return JSON.stringify(state); } });
assert.equal(interrupted.active.state, 'PAUSED');
assert.equal(interrupted.active.elapsedMs, 180000, '关闭时仅恢复已保存检查点，不累计退出时间');
startPractice(interrupted, '', null, at('12:00:00'));
finishPractice(interrupted, at('12:01:00'));
assert.equal(interrupted.history[0].durationSeconds, 240);
assert.equal(practiceToday(interrupted, at('12:02:00')).minutes, 4);
assert.equal(finishPractice(interrupted, at('12:02:00')), null, '重复结束不重复记账');
const midnight = createPractice();
startPractice(midnight, '<script>题目</script>', null, new Date('2026-10-14T23:59:30+08:00'));
finishPractice(midnight, new Date('2026-10-15T00:00:30+08:00'));
assert.deepEqual(midnight.history[0].dailyMs, { '2026-10-14': 30000, '2026-10-15': 30000 }, '跨天按真实区间分摊');
const suspended = createPractice();
startPractice(suspended, '休眠测试', null, at('10:00:00'));
checkpointPractice(suspended, at('10:00:01'));
checkpointPractice(suspended, at('11:00:00'));
assert.equal(suspended.active.state, 'PAUSED');
assert.equal(suspended.active.elapsedMs, 1000, '长时间计时回调中断不补计');
assert.throws(() => loadPractice({ getItem: () => '{broken' }));
assert.throws(() => loadPractice({ getItem: () => '{"version":9,"history":[]}' }));
console.log('✓ 独立练习：暂停、恢复、退出重开、长中断、跨天分摊、重复结束、异常记录保护通过');
